"""Cross-language protocol v1 parity verification tests.

Validates that JSON envelopes generated by the Kotlin Android client conform to
the Python validate_raw_message() implementation, and generates fixtures for
the Kotlin test suite to validate.
"""

import json
from pathlib import Path
import unittest
import uuid

from snow.protocol.constants import ErrorCode, MessageType, PROTOCOL_VERSION
from snow.protocol.models import SnowMessage, current_iso_timestamp
from snow.protocol.validator import ProtocolValidationError, validate_raw_message


def get_repo_root() -> Path:
    """Locate the repository root directory."""
    current = Path(__file__).resolve().parent
    while current.parent != current:
        if (current / "ARCHITECTURE.md").exists():
            return current
        current = current.parent
    return Path(__file__).resolve().parents[1]


FIXTURES_ROOT = get_repo_root() / "build" / "cross_language"
PY_TO_KT_VALID = FIXTURES_ROOT / "python_to_kotlin" / "valid"
PY_TO_KT_INVALID = FIXTURES_ROOT / "python_to_kotlin" / "invalid"
KT_TO_PY_VALID = FIXTURES_ROOT / "kotlin_to_python" / "valid"
KT_TO_PY_INVALID = FIXTURES_ROOT / "kotlin_to_python" / "invalid"


