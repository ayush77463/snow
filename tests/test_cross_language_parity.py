class TestCrossLanguageKotlinToPython(unittest.TestCase):
    """Direction A: Validate that Kotlin-generated JSON is parsed cleanly by Python."""

    @classmethod
    def setUpClass(cls) -> None:
        # Also ensure Python fixtures exist so running test suite standalone creates them
        generate_python_fixtures()

    def test_kotlin_to_python_fixtures(self) -> None:
        """Validate all Kotlin-generated fixtures using Python validate_raw_message()."""
        if not KT_TO_PY_VALID.exists() or not any(KT_TO_PY_VALID.glob("*.json")):
            self.skipTest(
                "Kotlin fixtures not yet generated. Run cross-language runner first."
            )

        valid_files = sorted(KT_TO_PY_VALID.glob("*.json"))
        self.assertGreater(len(valid_files), 0, "No Kotlin valid fixtures found.")

        for fpath in valid_files:
            raw_json = fpath.read_text(encoding="utf-8")
            with self.subTest(file=fpath.name):
                # Clean null omission check: optional fields must NOT be "field": null
                parsed_raw = json.loads(raw_json)
                self.assertNotIn(None, parsed_raw.values(), f"Explicit null found in {fpath.name}")

                msg = validate_raw_message(raw_json)
                self.assertEqual(msg.version, PROTOCOL_VERSION)
                self.assertIn(msg.type, set(MessageType))
                self.assertTrue(len(msg.id) == 36)
                self.assertTrue(msg.timestamp.endswith("Z") or "+00:00" in msg.timestamp)

        # Validate invalid fixtures
        if KT_TO_PY_INVALID.exists():
            expected_file = KT_TO_PY_INVALID / "expected_errors.json"
            if expected_file.exists():
                expected_map: dict[str, str] = json.loads(expected_file.read_text(encoding="utf-8"))
                for fname, expected_code in expected_map.items():
                    fpath = KT_TO_PY_INVALID / fname
                    if not fpath.exists():
                        continue
                    raw_json = fpath.read_text(encoding="utf-8")
                    with self.subTest(invalid_file=fname):
                        with self.assertRaises(ProtocolValidationError) as ctx:
                            validate_raw_message(raw_json)
                        self.assertEqual(
                            ctx.exception.code,
                            expected_code,
                            f"File {fname} expected {expected_code}, got {ctx.exception.code}",
                        )


