package org.snow.security

import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import java.security.KeyStore
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/**
 * Immutable data structure holding the IV and ciphertext resulting from an AES-GCM encryption.
 */
data class EncryptedPayload(
    val iv: ByteArray,
    val ciphertext: ByteArray
) {
    override fun equals(other: Any?): Boolean {
        if (this === other) return true
        if (javaClass != other?.javaClass) return false
        other as EncryptedPayload
        if (!iv.contentEquals(other.iv)) return false
        if (!ciphertext.contentEquals(other.ciphertext)) return false
        return true
    }

    override fun hashCode(): Int {
        var result = iv.contentHashCode()
        result = 31 * result + ciphertext.contentHashCode()
        return result
    }
}

/**
 * Interface abstracting secret key acquisition for AES-256-GCM operations.
 * Decouples AndroidKeyStore provider operations from JVM unit test suites.
 */
interface SecretKeyProvider {
    /**
     * Retrieve an existing AES-256 secret key, or generate a new one if it does not exist.
     */
    fun getOrCreateSecretKey(): SecretKey
}

/**
 * Production implementation backed by AndroidKeyStore.
 * Generates an AES-256 key inside the hardware-backed security module (TEE/StrongBox) when supported.
 */
class AndroidKeyStoreKeyProvider(
    private val keyAlias: String = DEFAULT_KEY_ALIAS
) : SecretKeyProvider {

    companion object {
        const val KEYSTORE_PROVIDER = "AndroidKeyStore"
        const val DEFAULT_KEY_ALIAS = "snow_auth_token_key"
        const val KEY_SIZE_BITS = 256
    }

    override fun getOrCreateSecretKey(): SecretKey {
        val keyStore = KeyStore.getInstance(KEYSTORE_PROVIDER).apply {
            load(null)
        }

        if (keyStore.containsAlias(keyAlias)) {
            val key = keyStore.getKey(keyAlias, null) as? SecretKey
            if (key != null) {
                return key
            }
        }

        val keyGenerator = KeyGenerator.getInstance(
            KeyProperties.KEY_ALGORITHM_AES,
            KEYSTORE_PROVIDER
        )

        val keyGenSpec = KeyGenParameterSpec.Builder(
            keyAlias,
            KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT
        )
            .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
            .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
            .setKeySize(KEY_SIZE_BITS)
            .setRandomizedEncryptionRequired(true)
            .build()

        keyGenerator.init(keyGenSpec)
        return keyGenerator.generateKey()
    }
}

/**
 * In-memory AES key provider for JVM unit tests, generating a standard AES-256 key via JCA.
 */
class InMemoryAesKeyProvider(
    private var secretKey: SecretKey = KeyGenerator.getInstance("AES").apply { init(256) }.generateKey()
) : SecretKeyProvider {

    override fun getOrCreateSecretKey(): SecretKey = secretKey

    fun setSecretKey(key: SecretKey) {
        this.secretKey = key
    }
}

/**
 * Cryptographic manager providing AES-256-GCM authenticated encryption and decryption.
 *
 * CRITICAL SECURITY INVARIANTS:
 * 1. Transformation: AES/GCM/NoPadding
 * 2. Key Size: 256 bits
 * 3. Authentication tag: 128 bits
 * 4. IV Length: strictly 12 bytes (96 bits) as recommended by NIST SP 800-38D
 * 5. Random IV: Automatically generated by the Cipher provider during ENCRYPT_MODE initialization;
 *    caller-generated IVs during encryption are prohibited.
 * 6. Decryption strictly enforces GCMParameterSpec(128, payload.iv) and verifies tag integrity.
 */
class KeyStoreManager(
    private val keyProvider: SecretKeyProvider
) {
    companion object {
        const val TRANSFORMATION = "AES/GCM/NoPadding"
        const val GCM_TAG_LENGTH_BITS = 128
        const val GCM_IV_LENGTH_BYTES = 12
    }

    /**
     * Encrypt plaintext bytes using AES-GCM with a randomized provider-generated IV.
     *
     * @param plaintext The unencrypted byte array. Must not be empty.
     * @return EncryptedPayload containing the 12-byte IV and ciphertext + auth tag.
     * @throws IllegalArgumentException if plaintext is empty.
     */
    fun encrypt(plaintext: ByteArray): EncryptedPayload {
        require(plaintext.isNotEmpty()) { "Plaintext cannot be empty" }

        val secretKey = keyProvider.getOrCreateSecretKey()
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, secretKey)

        val iv = cipher.iv ?: throw IllegalStateException("Cipher provider failed to generate IV")
        val ciphertext = cipher.doFinal(plaintext)

        return EncryptedPayload(iv = iv, ciphertext = ciphertext)
    }

    /**
     * Decrypt and verify authenticated ciphertext using AES-GCM.
     *
     * @param payload EncryptedPayload containing the 12-byte IV and ciphertext + auth tag.
     * @return Decrypted plaintext bytes.
     * @throws IllegalArgumentException if payload has empty fields or an invalid IV length.
     * @throws javax.crypto.AEADBadTagException if ciphertext, IV, or authentication tag is tampered with.
     */
    fun decrypt(payload: EncryptedPayload): ByteArray {
        require(payload.iv.isNotEmpty()) { "IV cannot be empty" }
        require(payload.ciphertext.isNotEmpty()) { "Ciphertext cannot be empty" }
        require(payload.iv.size == GCM_IV_LENGTH_BYTES) {
            "Invalid GCM IV length: expected $GCM_IV_LENGTH_BYTES bytes, got ${payload.iv.size}"
        }

        val secretKey = keyProvider.getOrCreateSecretKey()
        val cipher = Cipher.getInstance(TRANSFORMATION)
        val spec = GCMParameterSpec(GCM_TAG_LENGTH_BITS, payload.iv)
        cipher.init(Cipher.DECRYPT_MODE, secretKey, spec)

        return cipher.doFinal(payload.ciphertext)
    }
}
